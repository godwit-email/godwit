package uiclient

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"path"
	"slices"
	"strconv"
	"strings"
)

// customMethods are the callback-taking interface methods implemented in
// callbacks.go on top of their *Stream RPC counterparts.
var customMethods = map[string]bool{
	"DownloadRecognitionModel":              true,
	"FetchAttachments":                      true,
	"InlineImages":                          true,
	"InstallPluginFromRegistryWithProgress": true,
	"PrepareModelWithProgress":              true,
}

type paramSlot struct {
	name string
	typ  string
	expr ast.Expr
}

type parsedMethod struct {
	name    string
	params  []paramSlot
	results []paramSlot
	sigKey  string
	pkgs    map[string]bool
}

// Generate parses appServicePath and webuiServicePath and returns the formatted
// Go source for client_gen.go.
func Generate(appServicePath, webuiServicePath string) ([]byte, error) {
	fset := token.NewFileSet()
	imports := map[string]string{"context": "context"}
	methods := map[string]parsedMethod{}

	for _, srcPath := range []string{appServicePath, webuiServicePath} {
		f, err := parser.ParseFile(fset, srcPath, nil, 0)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", srcPath, err)
		}
		fileImports := map[string]string{}
		for _, im := range f.Imports {
			ip, err := strconv.Unquote(im.Path.Value)
			if err != nil {
				return nil, err
			}
			local := path.Base(ip)
			if im.Name != nil && im.Name.Name != "" {
				local = im.Name.Name
			}
			fileImports[local] = ip
			if prev, ok := imports[local]; ok && prev != ip {
				return nil, fmt.Errorf("conflicting import alias %q: %q vs %q", local, prev, ip)
			}
			imports[local] = ip
		}
		found := false
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, sp := range gd.Specs {
				ts, ok := sp.(*ast.TypeSpec)
				if !ok || ts.Name.Name != "Service" {
					continue
				}
				iface, ok := ts.Type.(*ast.InterfaceType)
				if !ok {
					return nil, fmt.Errorf("%s: Service is not an interface", srcPath)
				}
				found = true
				for _, field := range iface.Methods.List {
					ft, ok := field.Type.(*ast.FuncType)
					if !ok || len(field.Names) != 1 {
						return nil, fmt.Errorf("%s: unsupported embedded or multi-name method in Service", srcPath)
					}
					pm, err := parseMethod(fset, field.Names[0].Name, ft)
					if err != nil {
						return nil, fmt.Errorf("%s: %w", srcPath, err)
					}
					if prev, exists := methods[pm.name]; exists {
						if prev.sigKey != pm.sigKey {
							return nil, fmt.Errorf("method %s differs between interfaces: %s vs %s", pm.name, prev.sigKey, pm.sigKey)
						}
						continue
					}
					methods[pm.name] = pm
				}
			}
		}
		if !found {
			return nil, fmt.Errorf("%s: type Service interface not found", srcPath)
		}
	}

	var names []string
	for name := range methods {
		if customMethods[name] {
			continue
		}
		names = append(names, name)
	}
	slices.Sort(names)

	usedPkgs := map[string]bool{"context": true}
	var body bytes.Buffer
	for _, name := range names {
		pm := methods[name]
		for pkg := range pm.pkgs {
			usedPkgs[pkg] = true
		}
		code, err := emitMethod(pm)
		if err != nil {
			return nil, err
		}
		body.WriteString(code)
		body.WriteByte('\n')
	}

	var stdImports, extImports []string
	for local := range usedPkgs {
		ip, ok := imports[local]
		if !ok {
			return nil, fmt.Errorf("missing import path for %q", local)
		}
		spec := strconv.Quote(ip)
		if path.Base(ip) != local {
			spec = local + " " + spec
		}
		if strings.Contains(ip, ".") {
			extImports = append(extImports, spec)
		} else {
			stdImports = append(stdImports, spec)
		}
	}
	slices.Sort(stdImports)
	slices.Sort(extImports)

	var out bytes.Buffer
	out.WriteString("// Code generated by uiclient/cmd/gen; DO NOT EDIT.\n\n")
	out.WriteString("package uiclient\n\n")
	out.WriteString("import (\n")
	for _, s := range stdImports {
		fmt.Fprintf(&out, "\t%s\n", s)
	}
	if len(stdImports) > 0 && len(extImports) > 0 {
		out.WriteByte('\n')
	}
	for _, s := range extImports {
		fmt.Fprintf(&out, "\t%s\n", s)
	}
	out.WriteString(")\n\n")
	out.Write(body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w\n%s", err, out.String())
	}
	return formatted, nil
}

func parseMethod(fset *token.FileSet, name string, ft *ast.FuncType) (parsedMethod, error) {
	pkgs := map[string]bool{}
	collectPkgs := func(expr ast.Expr) {
		ast.Inspect(expr, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok {
					pkgs[id.Name] = true
				}
			}
			return true
		})
	}

	var params []paramSlot
	if ft.Params != nil {
		idx := 0
		for _, f := range ft.Params.List {
			if _, isFunc := f.Type.(*ast.FuncType); isFunc && !customMethods[name] {
				return parsedMethod{}, fmt.Errorf("method %s takes a callback func but is not in customMethods", name)
			}
			collectPkgs(f.Type)
			typStr := exprString(fset, f.Type)
			if len(f.Names) == 0 {
				params = append(params, paramSlot{name: fmt.Sprintf("arg%d", idx), typ: typStr, expr: f.Type})
				idx++
				continue
			}
			for _, n := range f.Names {
				pname := n.Name
				if pname == "" || pname == "_" {
					pname = fmt.Sprintf("arg%d", idx)
				} else if pname == "cl" {
					pname = "clArg"
				}
				params = append(params, paramSlot{name: pname, typ: typStr, expr: f.Type})
				idx++
			}
		}
	}

	var results []paramSlot
	if ft.Results != nil {
		for _, f := range ft.Results.List {
			collectPkgs(f.Type)
			typStr := exprString(fset, f.Type)
			count := max(1, len(f.Names))
			for range count {
				results = append(results, paramSlot{typ: typStr, expr: f.Type})
			}
		}
	}

	var pTypes, rTypes []string
	for _, p := range params {
		pTypes = append(pTypes, p.typ)
	}
	for _, r := range results {
		rTypes = append(rTypes, r.typ)
	}
	sigKey := "(" + strings.Join(pTypes, ",") + ")->(" + strings.Join(rTypes, ",") + ")"
	return parsedMethod{
		name:    name,
		params:  params,
		results: results,
		sigKey:  sigKey,
		pkgs:    pkgs,
	}, nil
}

func emitMethod(pm parsedMethod) (string, error) {
	var paramDecls []string
	for _, p := range pm.params {
		paramDecls = append(paramDecls, p.name+" "+p.typ)
	}
	var retSig string
	switch len(pm.results) {
	case 0:
	case 1:
		retSig = " " + pm.results[0].typ
	default:
		var rts []string
		for _, r := range pm.results {
			rts = append(rts, r.typ)
		}
		retSig = " (" + strings.Join(rts, ", ") + ")"
	}

	hasCtx := len(pm.params) > 0 && pm.params[0].typ == "context.Context"
	ctxExpr := "context.Background()"
	argStart := 0
	if hasCtx {
		ctxExpr = pm.params[0].name
		argStart = 1
	}
	var wireArgs []string
	for _, p := range pm.params[argStart:] {
		wireArgs = append(wireArgs, p.name)
	}
	tail := ""
	if len(wireArgs) > 0 {
		tail = ", " + strings.Join(wireArgs, ", ")
	}

	var callStmt string
	switch len(pm.results) {
	case 0:
		callStmt = fmt.Sprintf("callVoid(cl, %s, %q%s)", ctxExpr, pm.name, tail)
	case 1:
		if pm.results[0].typ == "error" {
			callStmt = fmt.Sprintf("return callErr(cl, %s, %q%s)", ctxExpr, pm.name, tail)
		} else {
			callStmt = fmt.Sprintf("return callVal[%s](cl, %s, %q%s)", pm.results[0].typ, ctxExpr, pm.name, tail)
		}
	case 2:
		if elem, ok := recvChanElem(pm.results[0].typ); ok && pm.results[1].typ == "error" {
			if !hasCtx {
				return "", fmt.Errorf("method %s: fallible stream must take context.Context", pm.name)
			}
			callStmt = fmt.Sprintf("return streamErr[%s](cl, %s, %q%s)", elem, ctxExpr, pm.name, tail)
		} else if elem, ok := recvChanElem(pm.results[0].typ); ok && pm.results[1].typ == "func()" {
			if hasCtx {
				return "", fmt.Errorf("method %s: streamStop does not take context.Context", pm.name)
			}
			callStmt = fmt.Sprintf("return streamStop[%s](cl, %q%s)", elem, pm.name, tail)
		} else if pm.results[1].typ == "error" {
			callStmt = fmt.Sprintf("return call[%s](cl, %s, %q%s)", pm.results[0].typ, ctxExpr, pm.name, tail)
		} else {
			return "", fmt.Errorf("unsupported 2-result signature for %s: %s", pm.name, pm.sigKey)
		}
	case 3:
		if pm.results[2].typ == "error" {
			callStmt = fmt.Sprintf("return call2[%s, %s](cl, %s, %q%s)", pm.results[0].typ, pm.results[1].typ, ctxExpr, pm.name, tail)
		} else {
			return "", fmt.Errorf("unsupported 3-result signature for %s: %s", pm.name, pm.sigKey)
		}
	default:
		return "", fmt.Errorf("unsupported result arity for %s: %s", pm.name, pm.sigKey)
	}

	return fmt.Sprintf("func (cl *Client) %s(%s)%s {\n\t%s\n}\n",
		pm.name, strings.Join(paramDecls, ", "), retSig, callStmt), nil
}

func recvChanElem(typ string) (string, bool) {
	elem, ok := strings.CutPrefix(typ, "<-chan ")
	return elem, ok
}

func exprString(fset *token.FileSet, expr ast.Expr) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, expr)
	return b.String()
}
